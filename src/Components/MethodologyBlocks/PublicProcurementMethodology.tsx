import { ParagraphText } from '@/Components/Typography';

function PublicProcurementMethodology() {
  return (
    <ParagraphText>
      Our public procurement integrity methodology uses a systemic approach to
      identify patterns (or "red flags") in public procurement that may be signs
      of corruption and other types of illicit behaviour. We use five widely
      available indicators to identify integrity risks at key stages of the
      procurement process.
      <br />
      <br />
      Remember: high risk values may not necessarily be evidence of corruption
      and could be influenced by underlying market structures. Regardless of
      whether a risk is an indicator of actual corruption, monitoring atypical
      procurement practices can help to identify and address underlying
      inefficiencies in the procurement system.
      <br />
      <br />
      The numerical value of an integrity indicator represents the number of
      risky contracts as a percentage of all measurable contracts for a given
      country or market. For example, if the procurement method can be measured
      for 100 contracts and 30 of them were awarded using non-open procedures,
      the indicator value will be 30. Countries are also assigned an indicator
      risk level based on its position relative to other countries (high,
      medium, or low).
      <br />
      <br />
      Within a country, the contracts can be analysed by product market,
      contract value, year, and sub-national regions, where data is available.
      <br />
      <br />
      Other important variables such as the transparency, size, and value of
      procurement can be measured using the data availability dashboards.
      <br />
      <br />
      The data was collected by the Government Transparency Institute (GTI) for
      UNDP’s Global Initiative on Measuring Corruption, from the publicly
      available data of national government procurement systems, then processed
      to create standardised, comparable datasets that enable analysis across
      countries and time.
    </ParagraphText>
  );
}

export default PublicProcurementMethodology;
